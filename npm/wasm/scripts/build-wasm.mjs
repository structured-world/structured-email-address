// Build the WebAssembly module and embed it: cargo → wasm-bindgen → wasm-opt,
// then the optimized bytes as base64 in generated/wasm-data.cjs, one module
// shared by the ESM and CJS builds (as structured-public-domains embeds its
// trie). Embedding means no asset for a bundler to locate and no fetch at
// startup. Everything under generated/ is build output and never committed.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)); // npm/wasm/scripts
const repo = join(here, "..", "..", "..");
const generated = join(here, "..", "generated");
const bindgenDir = join(generated, "bindgen");
const crate = "structured-email-address-wasm";
const raw = join(repo, "target", "wasm32-unknown-unknown", "wasm", "structured_email_address_wasm.wasm");
const bindgenWasm = join(bindgenDir, "structured_email_address_wasm_bg.wasm");
const optimized = join(generated, "module.wasm");

const run = (cmd, args) => execFileSync(cmd, args, { cwd: repo, stdio: ["ignore", "pipe", "inherit"], encoding: "utf8" });

// The bindgen schema is unstable, so the CLI must be the exact version the
// lockfile resolved for the crate.
const metadata = JSON.parse(run("cargo", ["metadata", "--format-version", "1", "--locked"]));
const locked = metadata.packages.find((p) => p.name === "wasm-bindgen")?.version;
const cli = run("wasm-bindgen", ["--version"]).trim().split(/\s+/)[1];
if (locked === undefined || cli !== locked) {
  throw new Error(
    `wasm-bindgen CLI ${cli} does not match the locked crate ${locked}; ` +
      `install it with: cargo install wasm-bindgen-cli --locked --version ${locked}`,
  );
}

run("cargo", ["build", "--locked", "-p", crate, "--target", "wasm32-unknown-unknown", "--profile", "wasm"]);

rmSync(generated, { recursive: true, force: true });
mkdirSync(bindgenDir, { recursive: true });
// `--omit-default-module-path`: the glue would otherwise reference a .wasm file
// next to itself via `new URL(..., import.meta.url)`, which bundlers try to
// resolve and which this package does not ship.
run("wasm-bindgen", ["--target", "web", "--omit-default-module-path", "--out-dir", bindgenDir, raw]);

// The features rustc enables by default for wasm32-unknown-unknown, so the
// optimizer neither rejects the module nor emits anything beyond them.
run("wasm-opt", [
  "-Os",
  "--enable-bulk-memory",
  "--enable-multivalue",
  "--enable-mutable-globals",
  "--enable-nontrapping-float-to-int",
  "--enable-reference-types",
  "--enable-sign-ext",
  bindgenWasm,
  "-o",
  optimized,
]);

const bytes = readFileSync(optimized);
writeFileSync(
  join(generated, "wasm-data.cjs"),
  '"use strict";\n' +
    "// Generated by scripts/build-wasm.mjs; do not edit.\n" +
    `exports.WASM_BASE64 = ${JSON.stringify(bytes.toString("base64"))};\n`,
);
writeFileSync(join(generated, "wasm-data.d.cts"), "export declare const WASM_BASE64: string;\n");
console.log(`module.wasm: ${bytes.length} bytes`);
