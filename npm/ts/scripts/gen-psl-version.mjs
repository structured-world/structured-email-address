// Generate generated/psl-version.ts: the structured-public-domains release
// installed at build time, whose psl.bin the WASM build checks byte for byte
// against the trie it embeds. The TypeScript backend downloads exactly that
// release by default. Runs on every build; the output is never committed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)); // npm/ts/scripts
const outDir = join(here, "..", "generated");

// The package exports psl.bin but not package.json; psl.bin sits in dist/.
const require = createRequire(join(here, "..", "package.json"));
const pslBin = require.resolve("@structured-world/structured-public-domains/psl.bin");
const { version } = JSON.parse(readFileSync(join(dirname(pslBin), "..", "package.json"), "utf8"));

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "psl-version.ts"),
  "// Generated by scripts/gen-psl-version.mjs; do not edit.\n" +
    `export const PSL_VERSION = ${JSON.stringify(version)};\n`,
);
console.log(`psl-version.ts: ${version}`);
